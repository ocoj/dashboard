#!/usr/bin/env node

/**
 * Build a flat English→Chinese translation map from the namespace-structured
 * en.ts / zh.ts files.  The output is written to `src/i18n/trans-map.ts`.
 *
 * Usage:
 *   node scripts/build-trans-map.js
 *
 * This is a one-time migration helper.  After the initial conversion the map
 * is maintained by hand (or re-run after bulk changes to en.ts / zh.ts).
 */

const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "src", "i18n", "messages");
const OUT = path.join(__dirname, "..", "src", "i18n", "trans-map.ts");

/**
 * Parse a TypeScript message file (en.ts / zh.ts) into a flat
 * Record<"namespace.key", "value">.
 *
 * The file must export a default object where each top-level key is a
 * namespace and the value is an object of string→string pairs.
 *
 * Supports two syntaxes for quoted strings:
 *   single-quoted: 'Hello'
 *   double-quoted: "Hello"
 *
 * Does NOT handle template literals with `${...}` interpolation (those
 * are intentionally skipped with a comment marker that can be fixed manually).
 */
function parseMessages(text) {
  const result = {};
  let currentNamespace = null;
  let braceDepth = 0;
  let inNamespace = false;

  // Process line by line, tracking which namespace we're inside.
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();

    // Track braces to know when we leave a namespace block.
    const opens = (line.match(/\{/g) || []).length;
    const closes = (line.match(/\}/g) || []).length;
    braceDepth += opens - closes;

    if (braceDepth <= 0) {
      currentNamespace = null;
      inNamespace = false;
      braceDepth = 0;
      continue;
    }

    // Detect namespace start:  `namespace: {`
    const nsMatch = line.match(/^(\w+)\s*:\s*\{/);
    if (nsMatch && braceDepth <= 1 + opens - closes) {
      currentNamespace = nsMatch[1];
      inNamespace = true;
      continue;
    }

    // Detect key: "value" or key: 'value' inside a namespace.
    if (inNamespace && currentNamespace) {
      // Match: key: "value"
      let m = line.match(/^(\w+)\s*:\s*"([^"]*)"/);
      if (!m) m = line.match(/^(\w+)\s*:\s*'([^']*)'/);
      if (m) {
        const key = m[1];
        const value = m[2];
        // Skip template-literal placeholders like `{count}` — these have
        // dynamic parts and must use a different mechanism.
        if (value.includes("$")) continue;
        result[`${currentNamespace}.${key}`] = value;
      }
    }
  }

  return result;
}

// ---- main ----------------------------------------------------------------

const enRaw = fs.readFileSync(path.join(SRC, "en.ts"), "utf-8");
const zhRaw = fs.readFileSync(path.join(SRC, "zh.ts"), "utf-8");

const en = parseMessages(enRaw);
const zh = parseMessages(zhRaw);

// Build English→Chinese map.  Only include keys that exist in BOTH files.
const map = {};
let matched = 0;
let unmatched = 0;

for (const [fullKey, english] of Object.entries(en)) {
  // First-wins: when multiple namespace keys produce the same English text
  // (e.g. common.save + untranslated.save_139), keep the first (proper)
  // translation instead of letting the untranslated fallback overwrite it.
  if (zh[fullKey] && !(english in map)) {
    map[english] = zh[fullKey];
    matched++;
  } else {
    unmatched++;
    console.warn(`  ⚠  Missing zh translation for: ${fullKey}`);
  }
}

// Also flag zh keys that don't have an en counterpart.
for (const fullKey of Object.keys(zh)) {
  if (!en[fullKey]) {
    console.warn(`  ⚠  Missing en key for: ${fullKey}`);
  }
}

// Generate output file.
const header = `/**
 * Flat English → Chinese translation map for the <TransText> component.
 *
 * AUTO-GENERATED by scripts/build-trans-map.js — DO NOT EDIT BY HAND.
 * To add translations, edit src/i18n/messages/en.ts and zh.ts, then re-run:
 *   node scripts/build-trans-map.js
 *
 * Generated: ${new Date().toISOString()}
 * Keys matched: ${matched} / ${Object.keys(en).length} en keys
 */
`;

const entries = Object.entries(map)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([en, zh]) => {
    // Escape any single quotes inside the strings for TS.
    const enEsc = en.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
    const zhEsc = zh.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
    return `  '${enEsc}': '${zhEsc}',`;
  });

const output = `${header}
const translations: Record<string, string> = {
${entries.join("\n")}
};

export default translations;
`;

fs.writeFileSync(OUT, output, "utf-8");

console.log(`✅  Wrote ${matched} translations to ${OUT}`);
if (unmatched) {
  console.log(`⚠   ${unmatched} en keys have no zh counterpart (see warnings above).`);
}
